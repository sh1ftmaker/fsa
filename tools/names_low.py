#!/usr/bin/env python3
"""Generate docs/names/LOW_CONFIDENCE.md from docs/names/names.tsv.

  python3 tools/names_low.py            # rewrite the library
  python3 tools/names_low.py --check    # exit 1 when the file is not what the manifest says

The library lists every row graded `low`: applied by owner decision
(2026-11-05) but the weakest evidence, so the first to revisit. The reason
and the "would confirm or replace" text come from the row's evidence (the
DEMOTED sentence, or the actors.tsv grade) and its kind. See METHOD.md.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs/names/names.tsv"
OUT = ROOT / "docs/names/LOW_CONFIDENCE.md"

MT = ("only evidence is a machine-translated Japanese label (actors.tsv `mt`); "
      "nothing in the unit corroborates the role")
ACTOR_LOW = "actors.tsv grades the actor name itself low ({what})"


def rows():
    for n, line in enumerate(MANIFEST.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#") or line.startswith("address\t"):
            continue
        f = line.split("\t")
        if len(f) != 7:
            sys.exit(f"names.tsv:{n}: expected 7 columns")
        yield dict(zip(("addr", "kind", "old", "new", "conf", "apply", "ev"), f))


def describe(r):
    """(reason, what would confirm or replace it, name_is_the_problem)"""
    ev = r["ev"]
    m = re.search(r"DEMOTED \(([^)]*)\): (.*)$", ev)
    if r["kind"] == "global":
        reason = m.group(2) if m else ev
        return (reason, "a name for the object's role that is proven (a string, a donor's "
                "equivalent, or enough documented use to name it); until then the name only "
                "restates the type", True)
    if m and "machine-translated" in m.group(2):
        return (MT, "the in-game English text (msg#) or a resource / string the unit loads "
                "naming the actor, or the same class in a donor game (TWW/TP); then med", False)
    a = re.search(r'actor (\w+) "([^"]*)" \(docs/names/actors.tsv, low\)', ev)
    if a:
        return (ACTOR_LOW.format(what=f'{a[1]} "{a[2]}"'),
                "an actors.tsv upgrade (msg# text, a matching wiki name, or a stage / texture "
                "cross-check); the class name follows it", False)
    return (m.group(2) if m else ev, "evidence that proves the role or the name", False)


def render():
    low = [r for r in rows() if r["conf"] == "low"]
    out = ["# Low-confidence names",
           "",
           "Generated by `tools/names_low.py` from `names.tsv`; do not edit. Regenerate after any",
           "manifest change (`python3 tools/names_low.py`, `--check` verifies).",
           "",
           "Owner decision (2026-11-05): low-confidence names are applied (`apply` = yes) but keep",
           "their honest grade. They are the weakest names in the tree and the first to revisit when",
           "new evidence turns up; promoting one means raising `confidence` in `names.tsv` once the",
           "evidence is there, replacing it means a new row (the address stays in the name either way).",
           "See METHOD.md.",
           "",
           f"{len(low)} rows: {sum(r['apply'] == 'yes' for r in low)} applied, "
           f"{sum(r['apply'] != 'yes' for r in low)} not applied.",
           "",
           "| new name | address | kind | old name | applied | why it is low | would confirm or replace it |",
           "|---|---|---|---|---|---|---|"]
    notes = []
    for r in sorted(low, key=lambda r: (r["kind"], r["addr"])):
        why, fix, bad = describe(r)
        out.append(f"| `{r['new']}` | {r['addr']} | {r['kind']} | `{r['old']}` | {r['apply']} | "
                   f"{why.replace('|', '/')} | {fix.replace('|', '/')} |")
        if bad:
            notes.append(f"- `{r['new']}`: the name itself is the problem, not the role. It is kept "
                         f"as recorded (no replacement was invented); a better role name needs evidence.")
    if notes:
        out += ["", "## Names that are weak in themselves", ""] + notes
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/names_low.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


sys.exit(main())
